#!/usr/bin/env python3
"""Programmatic maintenance of a repository's `specs/GRIEVANCES.md` ledger.

The ledger is a committed markdown file that carries, per grievance, a
machine-owned JSON header and a human-owned prose body:

    <!-- grievance:GRV-0001 {"id": "GRV-0001", ...} -->
    <a id="grv-0001"></a>
    ### GRV-0001 - high - 2026-07-30 - short description

    `internal/worker/main.go:42` - declared in spec 156 review

    <!-- grievance:GRV-0001:prose -->

    **Finding.** ...
    <!-- /grievance:GRV-0001 -->

Those JSON headers are the single source of truth. The two index tables at the
top of the file (open grievances, then resolved ones) are DERIVED: every
mutation regenerates them and re-sorts both chronologically.

Ownership contract:
  - the tool owns the index tables, the `<!-- grievance:... -->` markers, the
    anchor, the `###` heading, the context line and the resolution log lines;
  - everything after `<!-- grievance:ID:prose -->` is yours, kept verbatim.

Usage:
    grievances.py init
    grievances.py add --short "..." --severity high [--locus f.go:42] [--finding ...]
    grievances.py resolve GRV-0001 --commit 1a2b3c4 [--note "..."]
    grievances.py resolve GRV-0002 --wont-fix --note "..."
    grievances.py resolve GRV-0003 --promoted-to specs/156-cdar-refresh/ --note "..."
    grievances.py reopen GRV-0001 --note "..."
    grievances.py bump GRV-0001
    grievances.py list [--status open|resolved|all] [--json]
    grievances.py show GRV-0001 [--json]
    grievances.py rebuild
    grievances.py check [--strict] [--all --root <pilot-root>]
    grievances.py migrate [--from specs/DOLEANCES.md]

Convention and lifecycle: the `grievances` skill (SKILL.md beside this script).
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

LEDGER_BASENAME = "GRIEVANCES.md"
LEGACY_BASENAMES = ("DOLEANCES.md",)
SEVERITIES = ("critical", "high", "medium", "low")
RESOLUTION_KINDS = ("fixed", "wont-fix", "promoted")

OPEN_START = "<!-- grievances:index:open:start -->"
OPEN_END = "<!-- grievances:index:open:end -->"
RESOLVED_START = "<!-- grievances:index:resolved:start -->"
RESOLVED_END = "<!-- grievances:index:resolved:end -->"
# New detail blocks are inserted just before this marker, so a migrated file keeps
# its imported legacy prose below the indexed grievances.
DETAILS_END = "<!-- grievances:details:end -->"
GENERATED_NOTE = (
    "<!-- Generated by the `grievances` skill CLI. Do not edit these tables by hand: "
    "they are rebuilt from the JSON headers under `# Details` on every mutation. -->"
)

# Trailing blank lines are part of the match so that re-rendering normalizes the
# spacing between blocks instead of growing it on every mutation.
BLOCK_RE = re.compile(
    r"<!-- grievance:(GRV-\d{4}) (\{.*?\}) -->\n(.*?)<!-- /grievance:\1 -->\n*",
    re.DOTALL,
)
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
COMMIT_RE = re.compile(r"^[0-9a-fA-F]{7,40}$")
ID_RE = re.compile(r"^GRV-\d{4}$")


class UserError(Exception):
    """A problem the caller can fix by changing the command line."""


# ── Model ──────────────────────────────────────────────────────────────────


@dataclass
class Grievance:
    id: str
    short: str
    severity: str
    date: str
    status: str = "open"
    occurrences: int = 1
    locus: str | None = None
    source: str | None = None
    tags: list[str] = field(default_factory=list)
    resolution: dict[str, Any] | None = None
    history: list[dict[str, Any]] = field(default_factory=list)

    @property
    def anchor(self) -> str:
        return self.id.lower()

    @classmethod
    def from_meta(cls, meta: dict[str, Any]) -> "Grievance":
        known = {f for f in cls.__dataclass_fields__}  # type: ignore[attr-defined]
        unknown = set(meta) - known
        if unknown:
            raise UserError(f"{meta.get('id', '?')}: unknown JSON field(s): {sorted(unknown)}")
        return cls(**meta)

    def to_meta(self) -> dict[str, Any]:
        meta: dict[str, Any] = {
            "id": self.id,
            "short": self.short,
            "severity": self.severity,
            "date": self.date,
            "status": self.status,
            "occurrences": self.occurrences,
        }
        if self.locus:
            meta["locus"] = self.locus
        if self.source:
            meta["source"] = self.source
        if self.tags:
            meta["tags"] = self.tags
        if self.resolution:
            meta["resolution"] = self.resolution
        if self.history:
            meta["history"] = self.history
        return meta

    # ── Rendering (tool-owned lines) ───────────────────────────────────────

    def heading(self) -> str:
        seen = f" · ×{self.occurrences}" if self.occurrences > 1 else ""
        return f"### {self.id} · {self.severity} · {self.date}{seen} — {self.short}"

    def context_line(self) -> str | None:
        parts: list[str] = []
        if self.locus:
            parts.append(f"`{self.locus}`")
        if self.source:
            parts.append(f"declared in {self.source}")
        if self.tags:
            parts.append("tags: " + ", ".join(f"`{t}`" for t in self.tags))
        return " · ".join(parts) if parts else None

    @staticmethod
    def render_log_entry(entry: dict[str, Any]) -> str:
        action = entry.get("action")
        date = entry.get("date", "?")
        note = (entry.get("note") or "").strip()
        if action == "reopened":
            line = f"**Reopened {date}**"
            return f"{line} — {note}" if note else line
        kind = entry.get("kind", "fixed")
        if kind == "fixed":
            line = f"**Resolved {date}**"
            if note:
                line += f" — {note}"
            commit = entry.get("commit")
            if commit:
                line += f" · `{commit}`"
            return line
        if kind == "wont-fix":
            line = f"**Closed {date} — won't fix**"
            return f"{line} — {note}" if note else line
        line = f"**Closed {date} — promoted**"
        if note:
            line += f" — {note}"
        ref = entry.get("ref")
        if ref:
            line += f" → `{ref}`"
        return line

    def resolution_cells(self) -> tuple[str, str]:
        """(resolved date, commit-or-ref) cells for the resolved index table."""
        res = self.resolution or {}
        date = res.get("date", "")
        kind = res.get("kind", "fixed")
        if kind == "fixed":
            commit = res.get("commit", "")
            return date, f"`{commit}`" if commit else ""
        if kind == "wont-fix":
            return date, "won't fix"
        ref = res.get("ref", "")
        return date, f"promoted → `{ref}`" if ref else "promoted"


# ── File parsing / rendering ───────────────────────────────────────────────


@dataclass
class Ledger:
    path: Path
    text: str
    grievances: list[Grievance]
    prose: dict[str, str]

    @classmethod
    def load(cls, path: Path) -> "Ledger":
        if not path.is_file():
            raise UserError(
                f"no ledger at {path}\n"
                f"create it with: {Path(sys.argv[0]).name} init --file {path}"
            )
        text = path.read_text(encoding="utf-8")
        for marker in (OPEN_START, OPEN_END, RESOLVED_START, RESOLVED_END):
            if marker not in text:
                raise UserError(
                    f"{path}: missing index marker {marker}\n"
                    "this file predates the programmatic format — run: "
                    f"{Path(sys.argv[0]).name} migrate --from {path}"
                )
        grievances: list[Grievance] = []
        prose: dict[str, str] = {}
        seen: set[str] = set()
        for match in BLOCK_RE.finditer(text):
            gid, raw_meta, body = match.group(1), match.group(2), match.group(3)
            try:
                meta = json.loads(raw_meta)
            except json.JSONDecodeError as exc:
                raise UserError(f"{path}: {gid} has an unparseable JSON header: {exc}") from exc
            if meta.get("id") != gid:
                raise UserError(f"{path}: {gid} marker disagrees with its JSON id {meta.get('id')!r}")
            if gid in seen:
                raise UserError(f"{path}: {gid} appears twice")
            seen.add(gid)
            grievances.append(Grievance.from_meta(meta))
            prose[gid] = extract_prose(gid, body)
        return cls(path=path, text=text, grievances=grievances, prose=prose)

    def get(self, gid: str) -> Grievance:
        for g in self.grievances:
            if g.id == gid:
                return g
        raise UserError(f"{self.path}: no such grievance: {gid}")

    def next_id(self) -> str:
        numbers = [int(g.id.split("-")[1]) for g in self.grievances]
        return f"GRV-{max(numbers, default=0) + 1:04d}"

    def append(self, g: Grievance, prose: str) -> None:
        self.grievances.append(g)
        self.prose[g.id] = prose
        block = render_block(g, prose)
        matches = list(BLOCK_RE.finditer(self.text))
        if DETAILS_END in self.text:
            insert_at = self.text.index(DETAILS_END)
            self.text = self.text[:insert_at] + block + "\n" + self.text[insert_at:]
        elif matches:
            insert_at = matches[-1].end()
            self.text = self.text[:insert_at] + block + "\n" + self.text[insert_at:]
        else:
            self.text = self.text.rstrip("\n") + "\n\n" + block

    def render(self) -> str:
        text = self.text
        # Rewrite every detail block from its (possibly mutated) model.
        def replace(match: re.Match[str]) -> str:
            gid = match.group(1)
            return render_block(self.get(gid), self.prose[gid]) + "\n"

        text = BLOCK_RE.sub(replace, text)
        text = replace_region(text, OPEN_START, OPEN_END, self.render_open_index())
        text = replace_region(text, RESOLVED_START, RESOLVED_END, self.render_resolved_index())
        return text.rstrip("\n") + "\n"

    def render_open_index(self) -> str:
        rows = sorted(
            (g for g in self.grievances if g.status == "open"),
            key=lambda g: (g.date, g.id),
        )
        lines = [GENERATED_NOTE, "", f"## Open grievances ({len(rows)})", ""]
        if not rows:
            lines.append("_None._")
            return "\n".join(lines)
        lines += [
            "| ID | Date | Severity | Seen | Short description |",
            "|---|---|---|---|---|",
        ]
        for g in rows:
            lines.append(
                f"| [{g.id}](#{g.anchor}) | {g.date} | {g.severity} | ×{g.occurrences} "
                f"| {cell(g.short)} |"
            )
        return "\n".join(lines)

    def render_resolved_index(self) -> str:
        rows = sorted(
            (g for g in self.grievances if g.status == "resolved"),
            key=lambda g: ((g.resolution or {}).get("date", ""), g.id),
        )
        lines = [f"## Resolved grievances ({len(rows)})", ""]
        if not rows:
            lines.append("_None._")
            return "\n".join(lines)
        lines += [
            "| ID | Date | Severity | Seen | Short description | Resolved | Commit |",
            "|---|---|---|---|---|---|---|",
        ]
        for g in rows:
            resolved_date, ref = g.resolution_cells()
            lines.append(
                f"| [{g.id}](#{g.anchor}) | {g.date} | {g.severity} | ×{g.occurrences} "
                f"| {cell(g.short)} | {resolved_date} | {cell(ref)} |"
            )
        return "\n".join(lines)


def extract_prose(gid: str, body: str) -> str:
    """Return the human-owned part of a detail block."""
    marker = f"<!-- grievance:{gid}:prose -->"
    if marker in body:
        return body.split(marker, 1)[1].strip("\n")
    # Hand-written or pre-marker block: everything after the `###` heading.
    lines = body.split("\n")
    for i, line in enumerate(lines):
        if line.startswith("### "):
            return "\n".join(lines[i + 1 :]).strip("\n")
    return body.strip("\n")


def render_block(g: Grievance, prose: str) -> str:
    meta = json.dumps(g.to_meta(), ensure_ascii=False, sort_keys=True)
    lines = [
        f"<!-- grievance:{g.id} {meta} -->",
        f'<a id="{g.anchor}"></a>',
        g.heading(),
    ]
    context = g.context_line()
    if context:
        lines += ["", context]
    for entry in g.history:
        lines += ["", Grievance.render_log_entry(entry)]
    lines += ["", f"<!-- grievance:{g.id}:prose -->"]
    prose = prose.strip("\n")
    if prose:
        lines += ["", prose]
    lines += ["", f"<!-- /grievance:{g.id} -->"]
    return "\n".join(lines) + "\n"


def replace_region(text: str, start: str, end: str, body: str) -> str:
    head, _, rest = text.partition(start)
    _, _, tail = rest.partition(end)
    return f"{head}{start}\n{body}\n{end}{tail}"


def cell(value: str) -> str:
    return value.replace("|", r"\|").replace("\n", " ").strip()


# ── Validation helpers ─────────────────────────────────────────────────────


def today() -> str:
    return dt.date.today().isoformat()


def check_date(value: str | None) -> str:
    if value in (None, "", "today"):
        return today()
    assert value is not None
    if not DATE_RE.match(value):
        raise UserError(f"invalid date {value!r}: expected YYYY-MM-DD (or 'today')")
    try:
        dt.date.fromisoformat(value)
    except ValueError as exc:
        raise UserError(f"invalid date {value!r}: {exc}") from exc
    return value


def check_short(value: str) -> str:
    short = " ".join(value.split())
    if not short:
        raise UserError("--short must not be empty")
    if len(short) > 120:
        raise UserError(f"--short is {len(short)} chars; keep it under 120 (the long story goes in --finding)")
    return short


def check_id(value: str) -> str:
    if not ID_RE.match(value):
        raise UserError(f"invalid grievance id {value!r}: expected GRV-NNNN")
    return value


