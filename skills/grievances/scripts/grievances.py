# ── Path resolution ────────────────────────────────────────────────────────


def git_root(start: Path) -> Path | None:
    try:
        out = subprocess.run(
            ["git", "-C", str(start), "rev-parse", "--show-toplevel"],
            check=True,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return Path(out.stdout.strip())


def resolve_ledger_path(args: argparse.Namespace) -> Path:
    if getattr(args, "file", None):
        return Path(args.file).expanduser().resolve()
    env = os.environ.get("GRIEVANCES_FILE")
    if env:
        return Path(env).expanduser().resolve()
    repo = Path(getattr(args, "repo", None) or ".").expanduser().resolve()
    root = git_root(repo) or repo
    return root / "specs" / LEDGER_BASENAME


def write_text(path: Path, text: str, dry_run: bool) -> None:
    if dry_run:
        sys.stdout.write(text)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)


def save(ledger: Ledger, dry_run: bool) -> None:
    write_text(ledger.path, ledger.render(), dry_run)


def emit(payload: dict[str, Any], as_json: bool, human: str) -> None:
    if as_json:
        print(json.dumps(payload, ensure_ascii=False, sort_keys=True))
    else:
        print(human)


# ── Commands ───────────────────────────────────────────────────────────────


def cmd_init(args: argparse.Namespace) -> int:
    path = resolve_ledger_path(args)
    created: list[str] = []
    if path.exists():
        print(f"= {path} already exists — untouched")
    else:
        write_text(path, ledger_template(), args.dry_run)
        created.append(str(path))
        print(f"+ {path}")
    guidance = path.parent / "CLAUDE.md"
    if guidance.exists():
        if LEDGER_BASENAME not in guidance.read_text(encoding="utf-8"):
            print(f"! {guidance} exists but never mentions {LEDGER_BASENAME} — add the guidance by hand")
    else:
        write_text(guidance, specs_claude_template(), args.dry_run)
        created.append(str(guidance))
        print(f"+ {guidance}")
    root_claude = path.parent.parent / "CLAUDE.md"
    if not root_claude.exists():
        print(f"! no {root_claude} — nothing to point at the ledger from")
    elif f"specs/{LEDGER_BASENAME}" not in root_claude.read_text(encoding="utf-8"):
        print(f"! {root_claude} does not point at specs/{LEDGER_BASENAME}; paste this block into it:\n")
        print(ROOT_CLAUDE_POINTER)
    if created and not args.dry_run:
        print("commit: docs(grievances): add the non-blocking findings ledger and its scope guidance")
    return 0


def build_prose(args: argparse.Namespace) -> str:
    if getattr(args, "body_file", None):
        return Path(args.body_file).expanduser().read_text(encoding="utf-8").strip("\n")
    parts: list[str] = []
    if args.finding:
        parts.append(f"**Finding.** {args.finding.strip()}")
    if args.impact:
        parts.append(f"**Impact.** {args.impact.strip()}")
    if args.why_tests_miss:
        parts.append(f"**Why the tests miss it.** {args.why_tests_miss.strip()}")
    fix = (args.fix or "").strip()
    if fix or args.effort:
        line = f"**Fix.** {fix}" if fix else "**Fix.** _to be decided._"
        if args.effort:
            line += f" **Effort: {args.effort.strip()}.**"
        parts.append(line)
    return "\n\n".join(parts)


def cmd_add(args: argparse.Namespace) -> int:
    path = resolve_ledger_path(args)
    ledger = Ledger.load(path)
    short = check_short(args.short)
    date = check_date(args.date)
    if args.severity not in SEVERITIES:
        raise UserError(f"--severity must be one of {', '.join(SEVERITIES)}")
    if not args.force:
        needle = short.lower()
        for g in ledger.grievances:
            if g.status == "open" and g.short.lower() == needle:
                raise UserError(
                    f"{g.id} already carries this exact short description.\n"
                    f"met it again? bump the counter instead: grievances.py bump {g.id}\n"
                    "genuinely a distinct finding? re-run with --force"
                )
    if not args.impact and not args.body_file and not args.allow_no_impact:
        raise UserError(
            "--impact is required: an entry without an impact line gets ignored forever.\n"
            "pass --allow-no-impact only for a pure papercut whose cost is self-evident"
        )
    grievance = Grievance(
        id=ledger.next_id(),
        short=short,
        severity=args.severity,
        date=date,
        locus=args.locus,
        source=args.source,
        tags=list(args.tag or []),
    )
    ledger.append(grievance, build_prose(args))
    save(ledger, args.dry_run)
    emit(
        {"id": grievance.id, "file": str(path), "status": "open", "anchor": f"#{grievance.anchor}"},
        args.json,
        f"{grievance.id} declared ({grievance.severity}, {grievance.date}) in {path}",
    )
    return 0


def cmd_resolve(args: argparse.Namespace) -> int:
    path = resolve_ledger_path(args)
    ledger = Ledger.load(path)
    grievance = ledger.get(check_id(args.id))
    if grievance.status == "resolved" and not args.force:
        res = grievance.resolution or {}
        raise UserError(
            f"{grievance.id} is already resolved ({res.get('date')}, {res.get('kind')}). "
            "use --force to overwrite, or reopen it first"
        )
    date = check_date(args.date)
    selected = [flag for flag in (args.commit, args.wont_fix, args.promoted_to) if flag]
    if len(selected) != 1:
        raise UserError("pass exactly one of --commit <hash>, --wont-fix, --promoted-to <ref>")
    entry: dict[str, Any] = {"action": "resolved", "date": date}
    if args.commit:
        if not COMMIT_RE.match(args.commit):
            raise UserError(f"invalid commit hash {args.commit!r}: expected 7-40 hex characters")
        entry.update(kind="fixed", commit=args.commit.lower())
    elif args.wont_fix:
        if not args.note:
            raise UserError("--wont-fix requires --note: say why, in the file, once and for all")
        entry.update(kind="wont-fix")
    else:
        entry.update(kind="promoted", ref=args.promoted_to)
    if args.note:
        entry["note"] = args.note.strip()
    grievance.status = "resolved"
    grievance.resolution = {k: v for k, v in entry.items() if k != "action"}
    grievance.history.append(entry)
    save(ledger, args.dry_run)
    emit(
        {"id": grievance.id, "file": str(path), "status": "resolved", "resolution": grievance.resolution},
        args.json,
        f"{grievance.id} resolved ({entry['kind']}, {date}) in {path}",
    )
    return 0


def cmd_reopen(args: argparse.Namespace) -> int:
    path = resolve_ledger_path(args)
    ledger = Ledger.load(path)
    grievance = ledger.get(check_id(args.id))
    if grievance.status != "resolved":
        raise UserError(f"{grievance.id} is already open")
    date = check_date(args.date)
    entry: dict[str, Any] = {"action": "reopened", "date": date}
    if args.note:
        entry["note"] = args.note.strip()
    grievance.status = "open"
    grievance.resolution = None
    grievance.history.append(entry)
    save(ledger, args.dry_run)
    emit(
        {"id": grievance.id, "file": str(path), "status": "open"},
        args.json,
        f"{grievance.id} reopened ({date}) in {path}",
    )
    return 0


def cmd_bump(args: argparse.Namespace) -> int:
    path = resolve_ledger_path(args)
    ledger = Ledger.load(path)
    grievance = ledger.get(check_id(args.id))
    if grievance.status != "open":
        raise UserError(f"{grievance.id} is resolved — reopen it before counting a new occurrence")
    grievance.occurrences += 1
    if args.date or args.redate:
        grievance.date = check_date(args.date)
    save(ledger, args.dry_run)
    emit(
        {"id": grievance.id, "file": str(path), "occurrences": grievance.occurrences},
        args.json,
        f"{grievance.id} seen ×{grievance.occurrences}",
    )
    return 0


def cmd_list(args: argparse.Namespace) -> int:
    path = resolve_ledger_path(args)
    ledger = Ledger.load(path)
    rows = [g for g in ledger.grievances if args.status in ("all", g.status)]
    if args.severity:
        rows = [g for g in rows if g.severity in args.severity]
    rows.sort(key=lambda g: (g.date, g.id))
    if args.json:
        print(json.dumps([g.to_meta() for g in rows], ensure_ascii=False, sort_keys=True))
        return 0
    if not rows:
        print("no grievance matches")
        return 0
    for g in rows:
        seen = f" ×{g.occurrences}" if g.occurrences > 1 else ""
        suffix = ""
        if g.status == "resolved":
            resolved_date, ref = g.resolution_cells()
            suffix = f"  [resolved {resolved_date} {ref}]"
        print(f"{g.id}  {g.date}  {g.severity:<8}{seen:<4} {g.short}{suffix}")
    return 0


def cmd_show(args: argparse.Namespace) -> int:
    path = resolve_ledger_path(args)
    ledger = Ledger.load(path)
    grievance = ledger.get(check_id(args.id))
    if args.json:
        payload = grievance.to_meta()
        payload["prose"] = ledger.prose[grievance.id]
        print(json.dumps(payload, ensure_ascii=False, sort_keys=True))
        return 0
    sys.stdout.write(render_block(grievance, ledger.prose[grievance.id]))
    return 0


def cmd_rebuild(args: argparse.Namespace) -> int:
    path = resolve_ledger_path(args)
    ledger = Ledger.load(path)
    rendered = ledger.render()
    changed = rendered != ledger.text
    if args.dry_run:
        sys.stdout.write(rendered)
    elif changed:
        write_text(path, rendered, dry_run=False)
    print(f"{path}: {'rewritten' if changed else 'already normalized'}")
    return 0


def audit_repo(repo: Path, strict: bool) -> tuple[int, list[str]]:
    """Return (problem count, report lines) for one repository."""
    lines: list[str] = []
    problems = 0
    specs = repo / "specs"
    if not specs.is_dir():
        return 0, ["  ! no specs/ directory — nowhere canonical to host the ledger"]
    ledger_path = specs / LEDGER_BASENAME
    for legacy in LEGACY_BASENAMES:
        for stray in (repo / legacy, specs / legacy):
            if stray.is_file():
                problems += 1
                rel = stray.relative_to(repo)
                lines.append(f"  x legacy ledger present: {rel} — canonical name is specs/{LEDGER_BASENAME}")
                lines.append(f"    migrate it: grievances.py migrate --from {stray}")
    if (repo / LEDGER_BASENAME).is_file():
        problems += 1
        lines.append(f"  x misplaced at the repo root: {LEDGER_BASENAME} — move it to specs/")
    if not ledger_path.is_file():
        problems += 1
        lines.append(f"  x specs/{LEDGER_BASENAME} is MISSING — create it: grievances.py init --repo {repo}")
    else:
        try:
            ledger = Ledger.load(ledger_path)
        except UserError as exc:
            problems += 1
            lines.append(f"  x specs/{LEDGER_BASENAME}: {exc}")
        else:
            open_count = sum(1 for g in ledger.grievances if g.status == "open")
            resolved = len(ledger.grievances) - open_count
            lines.append(
                f"  v specs/{LEDGER_BASENAME} — {open_count} open, {resolved} resolved"
            )
            for g in ledger.grievances:
                if g.severity not in SEVERITIES:
                    problems += 1
                    lines.append(f"  x {g.id}: unknown severity {g.severity!r}")
                if not DATE_RE.match(g.date):
                    problems += 1
                    lines.append(f"  x {g.id}: date {g.date!r} is not YYYY-MM-DD")
                if g.status not in ("open", "resolved"):
                    problems += 1
                    lines.append(f"  x {g.id}: unknown status {g.status!r}")
                if g.status == "resolved":
                    res = g.resolution or {}
                    if res.get("kind") not in RESOLUTION_KINDS:
                        problems += 1
                        lines.append(f"  x {g.id}: resolved without a valid resolution kind")
                    elif res["kind"] == "fixed" and not COMMIT_RE.match(res.get("commit", "")):
                        problems += 1
                        lines.append(f"  x {g.id}: resolved as fixed without a commit hash")
                    if not DATE_RE.match(res.get("date", "")):
                        problems += 1
                        lines.append(f"  x {g.id}: resolved without a valid date")
                last = g.history[-1] if g.history else None
                expected = "resolved" if g.status == "resolved" else None
                if last and expected and last.get("action") != expected:
                    problems += 1
                    lines.append(f"  x {g.id}: status {g.status!r} contradicts its history")
            if strict and ledger.render() != ledger.text:
                problems += 1
                lines.append("  x file is not normalized (tables or headings drifted) — run: grievances.py rebuild")
    guidance = specs / "CLAUDE.md"
    if not guidance.is_file():
        problems += 1
        lines.append("  x specs/CLAUDE.md is MISSING (the when-to-read / when-to-write guidance)")
    elif LEDGER_BASENAME not in guidance.read_text(encoding="utf-8"):
        problems += 1
        lines.append(f"  x specs/CLAUDE.md never mentions {LEDGER_BASENAME}")
    root_claude = repo / "CLAUDE.md"
    if not root_claude.is_file():
        lines.append("  ! no root CLAUDE.md — nothing to point from")
    elif f"specs/{LEDGER_BASENAME}" not in root_claude.read_text(encoding="utf-8"):
        problems += 1
        lines.append(f"  x root CLAUDE.md does not point at specs/{LEDGER_BASENAME}")
    return problems, lines


def cmd_check(args: argparse.Namespace) -> int:
    if args.all:
        root = Path(args.root or ".").expanduser().resolve()
        repos = sorted(p.parent for p in root.glob("*/.git"))
        if not repos:
            print(f"no git repository found under {root}", file=sys.stderr)
            return 2
    else:
        target = resolve_ledger_path(args)
        repos = [target.parent.parent]
    total = 0
    compliant = 0
    for repo in repos:
        problems, lines = audit_repo(repo, args.strict)
        print(repo.name if args.all else str(repo))
        for line in lines:
            print(line)
        print()
        total += problems
        compliant += 1 if problems == 0 else 0
    print(f"{compliant}/{len(repos)} repo(s) compliant" + (f" · {total} problem(s)" if total else ""))
    return 0 if total == 0 else 1


def cmd_migrate(args: argparse.Namespace) -> int:
    target = resolve_ledger_path(args)
    if args.source:
        source = Path(args.source).expanduser().resolve()
    else:
        source = target.parent / LEGACY_BASENAMES[0]
    if not source.is_file():
        raise UserError(f"no legacy ledger at {source}")
    if source == target:
        raise UserError("source and target are the same file")
    if target.exists():
        raise UserError(f"{target} already exists — merge by hand, this command never overwrites")
    legacy = source.read_text(encoding="utf-8")
    body_lines = legacy.split("\n")
    if body_lines and body_lines[0].startswith("# "):
        body_lines = body_lines[1:]
    legacy_body = "\n".join(body_lines).strip("\n")
    migrated = (
        ledger_template().rstrip("\n")
        + "\n\n---\n\n"
        + f"## Legacy ledger — imported verbatim from `{source.name}` on {today()}\n\n"
        + "> Not indexed: these sessions predate the programmatic format and are kept\n"
        + "> as written. Anything still open here should be re-declared with\n"
        + "> `grievances.py add` so it appears in the table at the top, then struck\n"
        + "> from this section.\n\n"
        + legacy_body
        + "\n"
    )
    write_text(target, migrated, args.dry_run)
    if args.dry_run:
        return 0
    print(f"+ {target} (legacy content preserved under '## Legacy ledger')")
    if args.keep_legacy:
        print(f"= {source} kept (--keep-legacy)")
    else:
        removed = False
        if git_root(source.parent):
            removed = (
                subprocess.run(
                    ["git", "-C", str(source.parent), "rm", "--quiet", "--", source.name],
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                ).returncode
                == 0
            )
        if not removed:
            source.unlink()
        print(f"- {source}")
    guidance = target.parent / "CLAUDE.md"
    if guidance.is_file():
        print(f"! {guidance} still describes the old file — update its ledger section by hand")
    print(f"! update the repo root CLAUDE.md pointer to specs/{LEDGER_BASENAME}")
    print("commit: docs(grievances)!: rename the ledger to GRIEVANCES.md and index it programmatically")
    return 0


