def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="grievances.py",
        description="Declare, close and audit non-blocking findings in specs/GRIEVANCES.md.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    sub = parser.add_subparsers(dest="command", required=True)

    def with_common(p: argparse.ArgumentParser, *, json_flag: bool = True) -> argparse.ArgumentParser:
        p.add_argument("--file", help=f"ledger path (default: <git root>/specs/{LEDGER_BASENAME})")
        p.add_argument("--repo", help="repository root to resolve the default ledger path from")
        p.add_argument("--dry-run", action="store_true", help="print the resulting file, write nothing")
        if json_flag:
            p.add_argument("--json", action="store_true", help="machine-readable output")
        return p

    p_init = with_common(sub.add_parser("init", help="create the ledger and its specs/CLAUDE.md guidance"), json_flag=False)
    p_init.set_defaults(func=cmd_init)

    p_add = with_common(sub.add_parser("add", help="declare a grievance"))
    p_add.add_argument("--short", required=True, help="one-line description, under 120 chars (table column)")
    p_add.add_argument("--severity", required=True, choices=SEVERITIES)
    p_add.add_argument("--date", help="declaration date, YYYY-MM-DD (default: today)")
    p_add.add_argument("--locus", help="where it is observed, e.g. internal/worker/main.go:42")
    p_add.add_argument("--source", help="what surfaced it, e.g. 'spec 156 review'")
    p_add.add_argument("--tag", action="append", help="repeatable free-form tag")
    p_add.add_argument("--finding", help="what is observed")
    p_add.add_argument("--impact", help="what doing nothing costs (required)")
    p_add.add_argument("--why-tests-miss", help="why the suite does not catch it")
    p_add.add_argument("--fix", help="the direction of the fix")
    p_add.add_argument("--effort", help="indicative effort, e.g. 0.5d")
    p_add.add_argument("--body-file", help="read the whole prose body from this markdown file instead")
    p_add.add_argument("--allow-no-impact", action="store_true", help="papercut whose cost is self-evident")
    p_add.add_argument("--force", action="store_true", help="declare even if an open grievance has the same --short")
    p_add.set_defaults(func=cmd_add)

    p_res = with_common(sub.add_parser("resolve", help="close a grievance: date + commit hash"))
    p_res.add_argument("id")
    p_res.add_argument("--commit", help="commit hash that closed it (7-40 hex chars)")
    p_res.add_argument("--wont-fix", action="store_true", help="close without a fix; requires --note")
    p_res.add_argument("--promoted-to", help="close because it became a spec or a roadmap fiche")
    p_res.add_argument("--date", help="resolution date, YYYY-MM-DD (default: today)")
    p_res.add_argument("--note", help="one line on what closed it")
    p_res.add_argument("--force", action="store_true", help="overwrite an existing resolution")
    p_res.set_defaults(func=cmd_resolve)

    p_reo = with_common(sub.add_parser("reopen", help="move a resolved grievance back to the open table"))
    p_reo.add_argument("id")
    p_reo.add_argument("--date", help="reopening date, YYYY-MM-DD (default: today)")
    p_reo.add_argument("--note", help="why it is back")
    p_reo.set_defaults(func=cmd_reopen)

    p_bump = with_common(sub.add_parser("bump", help="count another occurrence instead of duplicating an entry"))
    p_bump.add_argument("id")
    p_bump.add_argument("--date", help="also move the entry's date to this one")
    p_bump.add_argument("--redate", action="store_true", help="also move the entry's date to today")
    p_bump.set_defaults(func=cmd_bump)

    p_list = with_common(sub.add_parser("list", help="list grievances"))
    p_list.add_argument("--status", choices=("open", "resolved", "all"), default="open")
    p_list.add_argument("--severity", action="append", choices=SEVERITIES)
    p_list.set_defaults(func=cmd_list)

    p_show = with_common(sub.add_parser("show", help="print one grievance"))
    p_show.add_argument("id")
    p_show.set_defaults(func=cmd_show)

    p_reb = with_common(sub.add_parser("rebuild", help="regenerate the tables and headings, re-sorted"), json_flag=False)
    p_reb.set_defaults(func=cmd_rebuild)

    p_chk = with_common(sub.add_parser("check", help="audit the ledger, its guidance and its pointers"), json_flag=False)
    p_chk.add_argument("--strict", action="store_true", help="also fail when the file is not normalized")
    p_chk.add_argument("--all", action="store_true", help="audit every git repo directly under --root")
    p_chk.add_argument("--root", help="pilot root holding the repos to audit (with --all)")
    p_chk.set_defaults(func=cmd_check)

    p_mig = with_common(sub.add_parser("migrate", help="rename a legacy DOLEANCES.md and index it"), json_flag=False)
    p_mig.add_argument("--from", dest="source", help=f"legacy ledger (default: <specs>/{LEGACY_BASENAMES[0]})")
    p_mig.add_argument("--keep-legacy", action="store_true", help="do not delete the legacy file")
    p_mig.set_defaults(func=cmd_migrate)

    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return int(args.func(args))
    except UserError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
